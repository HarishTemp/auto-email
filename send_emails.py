"""
Email Automation Using Python
-----------------------------
Topics Covered:
1. Sending emails using Python (smtplib, email.message.EmailMessage)
2. Reading recipient data from Excel using Pandas (pd.read_excel)
3. Dynamic email subject and personalized body content
4. Secure credential management via python-dotenv (.env file)
5. Safe Dry-Run / Test Mode for local demonstration and verification
"""

import os
import sys
import smtplib
from email.message import EmailMessage
import pandas as pd
from dotenv import load_dotenv

# Base directory for resolving file paths
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
EXCEL_PATH = os.path.join(BASE_DIR, "recipients.xlsx")
ENV_PATH = os.path.join(BASE_DIR, ".env")

# Load environment variables from .env file if it exists
load_dotenv(ENV_PATH)

SENDER_EMAIL = os.getenv("SENDER_EMAIL", "").strip()
SENDER_PASSWORD = os.getenv("SENDER_PASSWORD", "").strip()
SMTP_SERVER = os.getenv("SMTP_SERVER", "smtp.gmail.com").strip()
SMTP_PORT = int(os.getenv("SMTP_PORT", "465"))


def load_recipients(file_path):
    """
    Reads recipient details from an Excel file and validates required columns.
    """
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"Excel file not found at: {file_path}")

    print(f"[+] Reading recipient list from: {os.path.basename(file_path)}")
    df = pd.read_excel(file_path, engine="openpyxl")

    # Clean data: drop rows where Name or Email is missing
    df = df.dropna(subset=["Name", "Email"])
    print(f"[+] Loaded {len(df)} valid recipient records.\n")
    return df


def create_personalized_message(sender, recipient_name, recipient_email, event_name, reg_id):
    """
    Constructs a personalized email message using recipient's name and details.
    """
    msg = EmailMessage()
    msg["Subject"] = f"Confirmation: Welcome to the {event_name}, {recipient_name}!"
    msg["From"] = sender
    msg["To"] = recipient_email

    # Plain text version
    text_content = f"""Hello {recipient_name},

Thank you for registering for the upcoming {event_name}!

Here are your registration details:
---------------------------------------------
Recipient Name   : {recipient_name}
Registered Email : {recipient_email}
Event / Workshop : {event_name}
Registration ID  : {reg_id}
Status           : Confirmed
---------------------------------------------

We are excited to have you join us. Please keep this email for your records.
If you have any questions, feel free to reply to this email.

Best regards,
SMC Club Event Organizing Team
"""

    # Rich HTML version for modern email clients
    html_content = f"""<!DOCTYPE html>
<html>
<head>
  <style>
    body {{ font-family: Arial, sans-serif; line-height: 1.6; color: #333333; }}
    .container {{ max-width: 600px; margin: 20px auto; padding: 20px; border: 1px solid #e2e8f0; border-radius: 8px; background-color: #ffffff; }}
    .header {{ background-color: #1e3a8a; color: #ffffff; padding: 15px; border-radius: 6px 6px 0 0; text-align: center; }}
    .content {{ padding: 20px; }}
    .card {{ background-color: #f8fafc; border-left: 4px solid #3b82f6; padding: 12px 16px; margin: 15px 0; }}
    .footer {{ font-size: 12px; color: #64748b; text-align: center; margin-top: 20px; border-top: 1px solid #e2e8f0; padding-top: 10px; }}
  </style>
</head>
<body>
  <div class="container">
    <div class="header">
      <h2>SMC Club Event Registration Confirmation</h2>
    </div>
    <div class="content">
      <p>Hello <strong>{recipient_name}</strong>,</p>
      <p>Thank you for registering for the <strong>{event_name}</strong>. Your seat has been successfully reserved!</p>
      
      <div class="card">
        <p><strong>Registration ID:</strong> {reg_id}</p>
        <p><strong>Attendee:</strong> {recipient_name}</p>
        <p><strong>Email:</strong> {recipient_email}</p>
        <p><strong>Event:</strong> {event_name}</p>
        <p><strong>Status:</strong> <span style="color: #16a34a; font-weight: bold;">Confirmed</span></p>
      </div>

      <p>We look forward to seeing you there!</p>
      <p>Warm regards,<br><strong>SMC Club Organizing Team</strong></p>
    </div>
    <div class="footer">
      This is an automated notification generated by Python Email Automation.
    </div>
  </div>
</body>
</html>
"""

    msg.set_content(text_content)
    msg.add_alternative(html_content, subtype="html")
    return msg


def send_emails(df, dry_run=False):
    """
    Iterates through recipients and dispatches personalized emails.
    Supports secure real sending or safe simulation mode.
    """
    is_configured = bool(SENDER_EMAIL and SENDER_PASSWORD and SENDER_PASSWORD != "your_app_password_here")
    
    if dry_run or not is_configured:
        print("=" * 65)
        print(" [INFO] RUNNING IN TEST / SIMULATION MODE")
        if not is_configured:
            print(" (Sender credentials not configured in .env - simulating dispatch)")
        print("=" * 65)

        for idx, row in df.iterrows():
            name = str(row["Name"]).strip()
            email = str(row["Email"]).strip()
            event = str(row.get("Event", "Workshop")).strip()
            reg_id = str(row.get("Registration_ID", f"REG-{100+idx}")).strip()

            msg = create_personalized_message("smc-events@example.com", name, email, event, reg_id)
            print(f"[TEST SUCCESS] Email prepared for: {name} <{email}>")
            print(f"       Subject: {msg['Subject']}")
            print(f"       Event  : {event} | ID: {reg_id}")
            print("-" * 65)

        print("\nAll sample emails processed successfully in simulation mode.")
        print("To send live emails, configure your SENDER_EMAIL and SENDER_PASSWORD in .env")
        return

    # Real SMTP Dispatch Mode
    print(f"[+] Connecting to secure SMTP server: {SMTP_SERVER}:{SMTP_PORT}...")
    try:
        with smtplib.SMTP_SSL(SMTP_SERVER, SMTP_PORT) as server:
            server.login(SENDER_EMAIL, SENDER_PASSWORD)
            print("[+] Authenticated successfully with email server.\n")

            for idx, row in df.iterrows():
                name = str(row["Name"]).strip()
                email = str(row["Email"]).strip()
                event = str(row.get("Event", "Workshop")).strip()
                reg_id = str(row.get("Registration_ID", f"REG-{100+idx}")).strip()

                msg = create_personalized_message(SENDER_EMAIL, name, email, event, reg_id)
                server.send_message(msg)
                print(f"[+] Successfully sent personalized email to: {name} ({email})")

        print("\n[+] All recipient emails dispatched successfully!")
    except Exception as e:
        print(f"[-] SMTP error encountered: {e}")
        print("[-] Ensure you are using a 16-character Google App Password (not your normal account password).")


def main():
    dry_run = "--dry-run" in sys.argv
    df = load_recipients(EXCEL_PATH)
    send_emails(df, dry_run=dry_run)


if __name__ == "__main__":
    main()
